const SLOTS = new Map(DAYS.flatMap((d) => d.slots).map((s) => [s.id, s]));

const EXERCISES = new Map<string, { slot: Slot; exercise: Exercise }>();
for (const s of SLOTS.values()) {
  EXERCISES.set(s.exercise.key, { slot: s, exercise: s.exercise });
  if (s.substitute) EXERCISES.set(s.substitute.key, { slot: s, exercise: s.substitute });
}

export function getDay(id: DayId): Day {
  const d = DAYS.find((x) => x.id === id);
  if (!d) throw new Error(`Нет дня ${id}`);
  return d;
}

export function getSlot(id: string): Slot {
  const s = SLOTS.get(id);
  if (!s) throw new Error(`Нет упражнения ${id}`);
  return s;
}

export function exerciseByKey(key: string): { slot: Slot; exercise: Exercise } {
  const e = EXERCISES.get(key);
  if (!e) throw new Error(`Нет упражнения ${key}`);
  return e;
}

/** Есть ли в программе упражнение с таким ключом (основное или замена). */
export function isKnownKey(key: string): boolean {
  return EXERCISES.has(key);
}
