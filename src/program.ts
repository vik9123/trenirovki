export type DayId = 'tue' | 'thu' | 'sat';
export type Equipment = 'barbell' | 'smith' | 'dumbbell' | 'machine' | 'added';

export interface Exercise {
  key: string;
  name: string;
  equipment: Equipment;
  technique?: string;
  /** Мышцы: первой — основная (колонка «Мышцы» программы). */
  muscles?: string;
  /** Повторения — на каждую ногу или руку (вес — одной гантели или на блоке). */
  perSide?: 'leg' | 'arm';
}

export interface Slot {
  /** Постоянный id = ключ основного упражнения; не зависит от места в дне. */
  id: string;
  day: DayId;
  order: number;
  exercise: Exercise;
  sets: number;
  repMin: number;
  repMax: number;
  /** До скольких повторений растить, прежде чем прибавлять вес (разведения — до 20). */
  progressTo?: number;
  restSec: number;
  substitute?: Exercise;
}

export interface Day {
  id: DayId;
  title: string;
  short: string;
  kind: 'heavy' | 'light';
  note: string;
  warmup: string[];
  slots: Slot[];
}

